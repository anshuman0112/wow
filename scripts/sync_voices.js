// Pulls the voices from your ElevenLabs library into the WOW Voice Agent voice picker, with preview links.
//   npm run voices
// The ElevenLabs SDK reads ELEVENLABS_API_KEY from the environment (loaded from .env by
// `node --env-file=.env`). The key needs the "Voices → Read" permission.
import { ElevenLabsClient } from '@elevenlabs/elevenlabs-js';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pinnedVoices } from '../web/js/campaign-data.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const client = new ElevenLabsClient({ timeoutInSeconds: 30, maxRetries: 0 });

const toVoice = v => ({
  id: v.voiceId,
  name: v.name,
  category: v.category,                         // premade | professional | cloned | generated
  gender: v.labels?.gender || '',
  accent: v.labels?.accent || '',
  language: v.labels?.language || v.verifiedLanguages?.map(l => l.language).join(', ') || '',
  description: (v.description || v.labels?.description || v.labels?.descriptive || '').slice(0, 140),
  previewUrl: v.previewUrl || v.verifiedLanguages?.find(l => l.previewUrl)?.previewUrl || '',
  freePlanApi: v.category === 'premade',        // ElevenLabs free plan: only premade voices work via API
});

let all;
try {
  const res = await client.voices.getAll({ showLegacy: false });
  all = res.voices.map(toVoice);
} catch (e) {
  const code = e?.statusCode || e?.status;
  if (code === 401) {
    console.error('✗ ElevenLabs refused: the API key needs the "Voices → Read" permission.\n  elevenlabs.io → Settings → API Keys → edit the key → Voices: Read (or turn "Restrict key" off).');
  } else {
    console.error('✗ Could not list voices:', e?.message || e);
  }
  process.exit(1);
}

// Fill in preview links for the pinned voices (the ones you linked) if they're in your library.
const byId = new Map(all.map(v => [v.id, v]));
for (const p of pinnedVoices) {
  if (byId.has(p.id)) continue;
  try {
    byId.set(p.id, toVoice(await client.voices.get(p.id)));
  } catch { /* not in your library yet — it stays pinned without a preview */ }
}

// Your own library first (non-premade), then ElevenLabs' premade voices.
const list = [...byId.values()].sort((a, b) =>
  (a.category === 'premade') - (b.category === 'premade') || a.name.localeCompare(b.name));

const file = `// Generated by \`npm run voices\` (scripts/sync_voices.js) from your ElevenLabs library.
// Safe to commit: contains only public voice info and preview links, no keys.
export const libraryVoices = ${JSON.stringify(list, null, 2)};
export const syncedAt = ${JSON.stringify(new Date().toISOString())};
`;
await writeFile(path.join(root, 'web/js/voices.generated.js'), file);

const mine = list.filter(v => v.category !== 'premade');
console.log(`✓ ${list.length} voices saved to web/js/voices.generated.js`);
console.log(`  Your library (${mine.length}): ${mine.map(v => v.name).join(', ') || '—'}`);
console.log(`  Premade: ${list.length - mine.length}`);
